"""Markdown digest renderer."""

import os
from datetime import datetime


def render_digest(path: str, alerts: list, settings) -> None:
    """Write a markdown digest to *path*.

    Structure:
    - Header with run timestamp.
    - Baseline hash (last recorded).
    - Alert section (if any).
    - Quick‑look summary table.
    """
    ensured = os.path.dirname(path)
    os.makedirs(ensured, exist_ok=True)

    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    last_hash = getattr(settings, "last_baseline_hash", "—")[:16] + "…" if settings.last_baseline_hash else "—"

    lines = []
    lines.append("# Ekshop Site Sentinel — Security Digest")
    lines.append(f"**Run:** {now}")
    lines.append(f"**API base:** {settings.API_BASE_URL or 'not configured'}")
    lines.append(f"**Last baseline hash:** `{last_hash}`")
    lines.append("")

    if alerts:
        lines.append("## ⚠️ Alerts")
        for a in alerts:
            icon = {"critical": "🔴", "medium": "🟡", "low": "🟢"}.get(a["severity"], "⚪")
            lines.append(f"{icon} **[{a['severity'].upper()}] {a['type']}** — {a['detail']}")
        lines.append("")
    else:
        lines.append("## ✅ No alerts")
        lines.append("All checked properties are within expected bounds.")
        lines.append("")

    lines.append("## 📊 Quick look")
    lines.append(f"- API base: {settings.API_BASE_URL or 'not configured'}")
    lines.append(f"- Baseline hash (first 16): {last_hash}")
    lines.append(f"- Beacon verified: {'yes' if 'Beacon verified' in str(alerts) else 'N/A'}")
    lines.append("")

    lines.append("---")
    lines.append("_Generated by Ekshop Site Sentinel_")

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"🖨️  Digest written to {path}")